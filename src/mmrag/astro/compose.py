def _join(items: list[str]) -> str:
    return items[0] if len(items) == 1 else ", ".join(items[:-1]) + " and " + items[-1] if items else ""


def factual_sections(chart: NatalChart, on: date | None = None) -> str:
    """'Chart overview' and 'Key factors', written by code from the computed chart. Nothing in them is
    generated by a model."""
    on = on or date.today()
    p, lagna = chart.placements, chart.lagna
    stage = life_stage(chart.birth.when_local.date(), on)
    lagna_lord = SIGN_LORD[lagna.sign]
    ll = p[lagna_lord]
    occupied = [f"the {ordinal(h)} ({SIGNS[(SIGNS.index(lagna.sign) + h - 1) % 12]}): "
                f"{_join([b for b in BODIES if p[b].house == h])}"
                for h in range(1, 13) if any(p[b].house == h for b in BODIES)]
    md, ad = chart.current(on)
    lines = ["**Chart overview** _(calculated by software)_", "",
             f"{lagna.sign} Lagna at {dms(lagna.degree)}, in {lagna.nakshatra} nakshatra. The Lagna lord {lagna_lord} "
             f"is in {ll.sign} in the {ordinal(ll.house)} house"
             + (f" ({ll.dignity})" if ll.dignity else "") + ". "
             f"The Moon is in {p['Moon'].sign} in {p['Moon'].nakshatra} nakshatra (the {ordinal(p['Moon'].house)} "
             f"house). Planets by house: {'; '.join(occupied)}."]
    if md:
        lines.append(f"Running now: {md.lord} mahadasha until {md.end:%B %Y}"
                     + (f", in its {ad.sub} sub-period (antardasha) until {ad.end:%B %Y}." if ad else "."))
    lines.append(f"Age: {stage.age} ({stage.stage}).")

    strengths, challenges = [], []
    for b in BODIES:
        pl = p[b]
        if pl.dignity in ("exalted", "own sign"):
            strengths.append(f"{b} is {'exalted' if pl.dignity == 'exalted' else 'in its own sign'} in {pl.sign}, "
                             f"in the {ordinal(pl.house)} house ({HOUSE_MEANINGS[pl.house]}).")
        d9 = navamsa(pl.longitude)
        if d9 == pl.sign:
            strengths.append(f"{b} is Vargottama (in {d9} in both the birth chart and the Navamsa).")
    for nb in neecha_bhanga(chart):
        if nb.classical:
            strengths.append(f"{nb.body} is debilitated in {DEBILITATED[nb.body]}, but the debility is cancelled "
                             f"(neecha bhanga): {nb.classical[0]}.")
        else:
            challenges.append(f"{nb.body} is debilitated in {DEBILITATED[nb.body]} and the debility is not "
                              "cancelled by the classical rules" + (" (later rules cited: " + "; ".join(nb.later) + ")"
                                                                    if nb.later else "") + ".")
    for y in yogas(chart):
        if y.name == "Kemadruma":
            (strengths if "cancelled by" in y.condition else challenges).append(f"Kemadruma: {y.condition}.")
        else:
            strengths.append(f"{y.name}: {y.condition}.")
    for b in BODIES:
        pl = p[b]
        if pl.combust:
            challenges.append(f"{b} is combust (close to the Sun).")
        d9 = navamsa(pl.longitude)
        dig = navamsa_dignity(b, d9)
        if dig == "debilitated" and pl.dignity != "debilitated":
            challenges.append(f"{b} is debilitated in the Navamsa ({d9}).")
        if dig == "exalted":
            strengths.append(f"{b} is exalted in the Navamsa ({d9}).")
    lagna_aspects = [b for b, hs in aspects(chart).items() if 1 in hs]
    if lagna_aspects:
        strengths.append(f"The Lagna receives the aspect of {_join(lagna_aspects)}.")
    lines += ["", "**Key factors** _(calculated by software)_", ""]
    lines += [f"- Strength: {s}" for s in dict.fromkeys(strengths)]
    lines += [f"- Challenge: {c}" for c in dict.fromkeys(challenges)]
    return "\n".join(lines)


_STRIP_HEADINGS = re.compile(r"^\s*(?:#+\s*)?\**\s*(chart overview|relevant factors|key factors)\s*\**\s*:?\s*$", re.I)
_ANY_HEADING = re.compile(r"^\s*(?:#+\s*\S|\*\*[^*]{2,60}\*\*\s*:?\s*$)")


def strip_factual_sections(text: str) -> str:
    """Remove the model's own 'Chart overview' and 'Relevant factors' sections: code writes those."""
    out, skipping = [], False
    for line in text.splitlines():
        if _STRIP_HEADINGS.match(line):
            skipping = True
            continue
        if skipping and _ANY_HEADING.match(line):
            skipping = False
        if not skipping:
            out.append(line)
    return "\n".join(out).strip()


def collapse_repetition(text: str, max_repeats: int = 2) -> tuple[str, bool]:
    """Cut a generation loop: a line or sentence that keeps repeating (the Chennai reading of 2026-10-12
    listed '- the Moon is not in the 5th' until it hit the token limit). Returns (text, was_cut)."""
    lines, seen, out, cut = text.splitlines(), {}, [], False
    for line in lines:
        key = re.sub(r"\d+(st|nd|rd|th)?", "#", line.strip().lower())
        if key and len(key) > 8:
            seen[key] = seen.get(key, 0) + 1
            if seen[key] > max_repeats:
                cut = True
                continue
        out.append(line)
    return "\n".join(out), cut


def reference_facts(question: str) -> str:
    """Textbook facts from fixed tables for whatever the question names: nakshatras and their lords,
    signs and their rulers, a planet's dignities and significations, yoga definitions."""
    q = question.lower()
    lines = []
    for b in [*EXALTED, "Rahu", "Ketu"]:
        if re.search(rf"\b{b.lower()}\b", q):
            naks = [n for i, n in enumerate(NAKSHATRAS) if DASHA_ORDER[i % 9] == b]
            parts = [f"rules the nakshatras {_join(naks)}"]
            if b in EXALTED:
                parts += [f"owns {_join(OWN_SIGNS[b])}", f"is exalted in {EXALTED[b]} and debilitated in {DEBILITATED[b]}"]
            parts.append(f"signifies {KARAKA_OF[b]}")
            lines.append(f"- {b} " + "; ".join(parts) + ".")
    for i, n in enumerate(NAKSHATRAS):
        if re.search(rf"\b{n.lower()}\b", q):
            lines.append(f"- {n} nakshatra is ruled by {DASHA_ORDER[i % 9]} (Vimshottari lord); it spans "
                         f"{dms((i * 360 / 27) % 30)} {SIGNS[int(i * 360 / 27 // 30)]} to "
                         f"{dms(((i + 1) * 360 / 27) % 30 or 30)} {SIGNS[int(((i + 1) * 360 / 27 - 1e-9) // 30)]}.")
    for s in SIGNS:
        if re.search(rf"\b{s.lower()}\b", q):
            lines.append(f"- {s} is ruled by {SIGN_LORD[s]}.")
    for name, definition in YOGA_DEFINITIONS.items():
        if name.lower().split()[0] in q:
            lines.append(f"- {name} yoga: {definition}.")
    m = re.search(r"\b(\d{1,2})(?:st|nd|rd|th)\s+house\b", q)
    if m and 1 <= int(m.group(1)) <= 12:
        h = int(m.group(1))
        kinds = [k for k, s in (("a kendra", KENDRA), ("a trikona", TRIKONA), ("a dusthana", DUSTHANA)) if h in s]
        lines.append(f"- The {ordinal(h)} house signifies {HOUSE_MEANINGS[h]}" + (f"; it is {_join(kinds)}" if kinds
                                                                                 else "") + ".")
    if not lines:
        return ""
    return ("Reference facts from standard Parashari tables (correct; use them, never contradict them):\n"
            + "\n".join(dict.fromkeys(lines)))
