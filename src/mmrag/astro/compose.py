"""The parts of a reading that code writes, and clean-up of what the model writes (Phase 11, Level 1).

The Gemini judge (2026-10-12) found that most major errors were restated facts: the writer had the
correct chart facts and still wrote "the 3rd, a trikona" or "the Sun in his own sign". So the
factual sections (Chart overview, Key factors) are written here from the computed analysis, and the
model writes only the interpretation. Plain knowledge questions get reference facts from fixed
tables (nakshatra lords, sign rulers, dignities, significators, yoga definitions), because the
writer's own answers to them scored lowest of all.
"""

